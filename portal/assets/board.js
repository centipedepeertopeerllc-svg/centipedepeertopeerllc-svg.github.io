  function collect(manual, auto) {
    const today = todayISO();
    const out = [], keys = new Set(), nums = new Set();
    const push = (s) => {
      const k = normKey(s), n = policyNum(s);
      if (keys.has(k)) return;
      if (n && nums.has(n)) return;
      keys.add(k); if (n) nums.add(n);
      out.push(s);
    };
    (manual || []).filter((s) => isLive(s, today)).forEach(push);
    (auto || []).forEach(push);
    return out;
  }

