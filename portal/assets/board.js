"use strict";
/* Centipede Peer to Peer, LLC — Company Message Board (assets/board.js).
   The Portal's digital billboard (CPP-POL-2026-061): a slideshow at the
   top of the Portal home that rotates what is going on in the company —
   policy changes, company news, program updates — and gives Jarvis (and
   the CEO) a door to post straight to everyone in the Portal.

   How it works:
   - Slides the office posts by hand live in this device's local storage
     under "cpp.portal.board.v1": an array of
     { id, tag, headline, body, date, by, expires }. The store is seeded
     once per device with the current company items; after that, what is
     in the store is what shows (a retired slide stays retired).
   - On every load the board ALSO surfaces, automatically:
       * the newest entries from the Program Activity store
         ("cpp.portal.progact.v1"), and
       * the newest policies from the Company Documents policy gallery
         (documents/policies/index.html, fetched same-origin),
     so new postings appear on the board without anyone re-typing them.
     Automatic slides are deduplicated against the posted slides by
     headline + date, and by policy number for policy slides.
   - The slideshow advances every 8 seconds, pauses on hover / focus /
     tap, and carries previous/next arrows and slide dots.
   - The "Post to the board" composer is shown ONLY to levi.spears and
     jarvis. A post is signed "Jarvis" under the jarvis sign-in and
     "Levi Spears, CEO" under levi.spears. Those two can also retire
     (delete) any posted slide. Everyone signed in can read the board.
   - NO client information of any kind ever goes on this board — it is
     program- and company-level news only. No external libraries, no CDN.
   Built Nov 19, 2026 at the CEO's direction. */
(function () {
  const BOARD_KEY = "cpp.portal.board.v1";
  const SEEDED_KEY = "cpp.portal.board.seeded.v1";
  const PROGACT_KEY = "cpp.portal.progact.v1";
  const ROTATE_MS = 8000;
  const TAGS = ["POLICY", "COMPANY", "PROGRAM", "FROM JARVIS", "REMINDER"];
  const POSTERS = { "levi.spears": "Levi Spears, CEO", "jarvis": "Jarvis" };
  const PROG_NAMES = {
    "homeless-outreach": "Homeless Outreach",
    "peer-support": "1-on-1 Peer Support",
    "referrals-id": "Referrals & ID Assistance",
    "resource-navigation": "Community Resource Navigation",
    "justice-support": "Justice Support Program",
    "recovery-support": "Substance Abuse Recovery Support",
    "women-helping-women": "Women Helping Women",
    "super-hero": "Super Hero Program",
    "day-of-hope": "Centipede Day of Hope",
    "hygiene-outreach": "Hygiene",
    "homeless-shelter": "Shelter — Stockton",
    "veterans": "Veterans Program"
  };
  const KIND_LABEL = { done: "Done", updated: "Updated", coming: "Coming Up" };
  const MONTHS = { january: 1, february: 2, march: 3, april: 4, may: 5, june: 6, july: 7, august: 8, september: 9, october: 10, november: 11, december: 12 };

  /* Seeded slides — real company items as the record stood on
     Thursday, November 19, 2026. No client information. */
  const SEED = [
    { id: "SEED-WELCOME", tag: "FROM JARVIS", headline: "Welcome to the Company Message Board", body: "This board is the company's billboard: policy changes, company news, and program updates appear here automatically, and I post here to reach everyone in the Portal. The slides rotate on their own — hover, tap, or use the arrows to read at your own pace.", date: "2026-11-19", by: "Jarvis", expires: null },
    { id: "SEED-POL-060", tag: "POLICY", headline: "New policy issued — CPP-POL-2026-060, Company Email Passwords and IT Access", body: "Company email passwords will be generated by the company, and IT holds direct access to company mailboxes for updates, upgrades, and security. Effective December 1, 2026, with the company email upgrade. The full policy is in the Company Documents library.", date: "2026-11-19", by: "Jarvis", expires: null },
    { id: "SEED-POL-057-058", tag: "POLICY", headline: "Also issued this week — CPP-POL-2026-057 and CPP-POL-2026-058", body: "CPP-POL-2026-057 covers public appointment requests and the video visit notice; CPP-POL-2026-058 covers the Program Activity log. Both are posted in the Company Documents library — every policy, in one place.", date: "2026-11-19", by: "Jarvis", expires: null },
    { id: "SEED-DOH", tag: "PROGRAM", headline: "Centipede Day of Hope — invitation sent to Gospel Center Rescue Mission", body: "Our invitation went to the Mission this morning. The Day of Hope is planned for around March 2027: one free community service day with every provider in one place. Status: In Development — pending Board approval on November 27, 2026.", date: "2026-11-19", by: "Jarvis", expires: null },
    { id: "SEED-DEC1", tag: "COMPANY", headline: "December 1 — company email upgrade: @centipedepeertopeer.llc addresses arrive", body: "On December 1 the company moves to its own domain. Every staff member gets an address at centipedepeertopeer.llc, with the branded signature plate set up on each mailbox. Watch this board for your new address.", date: "2026-11-19", by: "Jarvis", expires: "2026-12-02" },
    { id: "SEED-MR-TRAINING", tag: "REMINDER", headline: "Mandated Reporter training — deadline December 18", body: "All current staff complete the Mandated Reporter training by December 18, 2026. See CPP-POL-2026-048 in the Company Documents library for the training path and the certificate record.", date: "2026-11-19", by: "Jarvis", expires: "2026-12-19" },
    { id: "SEED-TOM-START", tag: "COMPANY", headline: "Welcome, Tom Clark — first day Saturday, November 28", body: "Thomas Leo Clark III, our Certified Peer Support Specialist, starts on November 28, 2026. His desk is the Peer Support Dashboard — say hello when you see him.", date: "2026-11-19", by: "Jarvis", expires: "2026-11-29" }
  ];

  const $ = (id) => document.getElementById(id);
  const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  const pad2 = (n) => String(n).padStart(2, "0");
  function todayISO() { const d = new Date(); return d.getFullYear() + "-" + pad2(d.getMonth() + 1) + "-" + pad2(d.getDate()); }
  function fmtDay(d) { if (!d) return ""; try { return new Date(d + "T12:00:00").toLocaleDateString("en-US", { weekday: "short", month: "short", day: "numeric", year: "numeric" }); } catch { return d; } }
  function truncate(s, n) { s = String(s || ""); return s.length > n ? s.slice(0, n - 1).trimEnd() + "…" : s; }

  /* ---------------- the posted-slides store ---------------- */
  function loadStore() {
    let v = null;
    try { const raw = localStorage.getItem(BOARD_KEY); if (raw !== null) { const p = JSON.parse(raw); if (Array.isArray(p)) v = p; } } catch { v = null; }
    if (v === null) { v = []; saveStore(v); }
    let seeded = null;
    try { seeded = localStorage.getItem(SEEDED_KEY); } catch { seeded = null; }
    if (!seeded) {
      // First run on this device: seed once. After this, the store is
      // the record — a slide retired by the CEO or Jarvis stays retired.
      const have = new Set(v.map((s) => s.id));
      for (const s of SEED) if (!have.has(s.id)) v.push(Object.assign({}, s));
      saveStore(v);
      try { localStorage.setItem(SEEDED_KEY, "1"); } catch { /* storage blocked — seeding repeats harmlessly, ids dedupe */ }
    }
    return v;
  }
  function saveStore(v) { try { localStorage.setItem(BOARD_KEY, JSON.stringify(v)); } catch { /* storage full/blocked — the board still renders for this session */ } }
  function isLive(s, today) { return !s.expires || s.expires >= today; }

  /* ---------------- automatic slides ---------------- */
  function progactSlides(limit) {
    let entries = null;
    try { const raw = localStorage.getItem(PROGACT_KEY); if (raw !== null) { const p = JSON.parse(raw); if (Array.isArray(p)) entries = p; } } catch { entries = null; }
    if (!entries || !entries.length) return [];
    return entries.slice()
      .sort((a, b) => ((b.date || "") + (b.at || "")).localeCompare((a.date || "") + (a.at || "")))
      .slice(0, limit || 4)
      .map((e) => ({
        id: "AUTO-ACT-" + e.id,
        tag: "PROGRAM",
        headline: (PROG_NAMES[e.program] || e.program || "Program") + " — " + (KIND_LABEL[e.kind] || "Update"),
        body: truncate(e.text, 240),
        date: e.date || "",
        by: e.by || "Program Activity",
        expires: null,
        auto: true
      }));
  }
  function parsePolicyDate(st) {
    const m = String(st || "").match(/(\w+)\s+(\d{1,2}),\s*(\d{4})/);
    if (!m) return "";
    const mo = MONTHS[m[1].toLowerCase()];
    if (!mo) return "";
    return m[3] + "-" + pad2(mo) + "-" + pad2(Number(m[2]));
  }
  function policySlides(cards, limit) {
    return (cards || []).slice()
      .map((c) => ({ num: c.num, ttl: c.ttl, st: c.st, date: parsePolicyDate(c.st) }))
      .filter((c) => c.num && c.ttl)
      .sort((a, b) => (b.date || "").localeCompare(a.date || "") || b.num.localeCompare(a.num))
      .slice(0, limit || 5)
      .map((c) => ({
        id: "AUTO-POL-" + c.num,
        tag: "POLICY",
        headline: c.num + " — " + c.ttl,
        body: (c.st || "On the record") + ". Read the full policy in the Company Documents library.",
        date: c.date || "",
        by: "Company Policies",
        expires: null,
        auto: true
      }));
  }
  function parseGallery(html) {
    const doc = new DOMParser().parseFromString(html, "text/html");
    const cards = [];
    doc.querySelectorAll(".card").forEach((card) => {
      const num = card.querySelector(".num"), ttl = card.querySelector(".ttl"), st = card.querySelector(".st");
      if (num && ttl) cards.push({ num: num.textContent.trim(), ttl: ttl.textContent.trim(), st: st ? st.textContent.trim() : "" });
    });
    return cards;
  }

  /* ---------------- collect + dedupe ---------------- */
  function normKey(s) { return String(s.headline || "").toLowerCase().replace(/\s+/g, " ").trim() + "|" + (s.date || ""); }
  function policyNum(s) { const m = (String(s.headline || "") + " " + String(s.body || "")).match(/CPP-POL-\d{4}-\d{3}/); return m ? m[0] : null; }
  function collect(manual, auto) {
    const today = todayISO();
    const out = [], keys = new Set(), nums = new Set();
    const push = (s) => {
      const k = normKey(s), n = policyNum(s);
      if (keys.has(k)) return;
      if (n && nums.has(n)) return;
      keys.add(k); if (n) nums.add(n);
      out.push(s);
    };
    (manual || []).filter((s) => isLive(s, today)).forEach(push);
    (auto || []).forEach(push);
    return out;
  }

  /* ---------------- slideshow ---------------- */
  const ui = { user: null, slides: [], idx: 0, timer: null, paused: false, bound: false };
  function nextIndex(i, n, dir) { if (!n) return 0; return ((i + dir) % n + n) % n; }

  function tagClass(tag) {
    return { "POLICY": "tag-policy", "COMPANY": "tag-company", "PROGRAM": "tag-program", "FROM JARVIS": "tag-jarvis", "REMINDER": "tag-reminder" }[tag] || "tag-company";
  }
  function draw() {
    const stage = $("board-stage");
    if (!stage) return;
    if (!ui.slides.length) {
      stage.innerHTML = '<p class="board-body">No slides on the board right now — new company news will appear here.</p>';
      const dots = $("board-dots"); if (dots) dots.innerHTML = "";
      const count = $("board-count"); if (count) count.textContent = "";
      return;
    }
    if (ui.idx >= ui.slides.length) ui.idx = 0;
    stage.innerHTML = ui.slides.map((s, i) =>
      `<article class="board-slide${i === ui.idx ? " active" : ""}" aria-hidden="${i === ui.idx ? "false" : "true"}">
         <span class="board-tag ${tagClass(s.tag)}">${esc(s.tag)}</span>
         <h3 class="board-headline">${esc(s.headline)}</h3>
         <p class="board-body">${esc(s.body)}</p>
         <p class="board-meta">${esc(fmtDay(s.date))} · Posted by ${esc(s.by)}</p>
       </article>`).join("");
    const dots = $("board-dots");
    if (dots) {
      dots.innerHTML = ui.slides.map((s, i) => `<button type="button" class="board-dot${i === ui.idx ? " active" : ""}" data-dot="${i}" aria-label="Slide ${i + 1}: ${esc(s.headline)}"></button>`).join("");
      dots.querySelectorAll("[data-dot]").forEach((b) => b.addEventListener("click", () => { goTo(Number(b.getAttribute("data-dot"))); restart(); }));
    }
    const count = $("board-count");
    if (count) count.textContent = "Slide " + (ui.idx + 1) + " of " + ui.slides.length + (ui.paused ? " · paused" : "");
  }
  function goTo(i) { ui.idx = i; draw(); }
  function step(dir) { if (ui.slides.length > 1) { ui.idx = nextIndex(ui.idx, ui.slides.length, dir); draw(); } }
  function stopTimer() { if (ui.timer !== null) { clearInterval(ui.timer); ui.timer = null; } }
  function startTimer() {
    stopTimer();
    if (ui.slides.length < 2) return;
    let reduced = false;
    try { reduced = window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches; } catch { reduced = false; }
    if (reduced) return;
    ui.timer = setInterval(() => { if (!ui.paused) step(1); }, ROTATE_MS);
  }
  function restart() { startTimer(); }
  function setPaused(p) { ui.paused = p; const count = $("board-count"); if (count && ui.slides.length) count.textContent = "Slide " + (ui.idx + 1) + " of " + ui.slides.length + (ui.paused ? " · paused" : ""); }

  /* ---------------- composer + retire (levi.spears / jarvis only) ---------------- */
  function canPost() { return !!(ui.user && POSTERS[ui.user.username]); }
  function renderComposer() {
    const box = $("board-composer");
    if (!box) return;
    if (!canPost()) { box.hidden = true; return; }
    box.hidden = false;
    const tagSel = $("board-tag");
    if (tagSel && !tagSel.options.length) {
      tagSel.innerHTML = TAGS.map((t) => `<option${t === (ui.user.username === "jarvis" ? "FROM JARVIS" : "COMPANY") ? " selected" : ""}>${esc(t)}</option>`).join("");
    }
    renderManage();
  }
  function renderManage() {
    const wrap = $("board-manage");
    if (!wrap || !canPost()) return;
    const store = loadStore();
    wrap.innerHTML = "<h4>Slides on this device's board — retire one to take it down</h4>" + (store.length
      ? "<ul>" + store.map((s) => `<li><span><strong>${esc(s.headline)}</strong><br><span class="hint">${esc(s.tag)} · ${esc(fmtDay(s.date))} · ${esc(s.by)}</span></span><button type="button" class="btn-small" data-retire="${esc(s.id)}">Retire</button></li>`).join("") + "</ul>"
      : '<p class="hint">No posted slides in the store right now.</p>');
    wrap.querySelectorAll("[data-retire]").forEach((b) => b.addEventListener("click", () => {
      saveStore(loadStore().filter((s) => s.id !== b.getAttribute("data-retire")));
      refresh();
      const msg = $("board-msg"); if (msg) msg.textContent = "Slide retired.";
      renderManage();
    }));
  }
  function onPost(e) {
    e.preventDefault();
    if (!canPost()) return;
    const headline = $("board-headline").value.trim();
    const body = $("board-body").value.trim();
    if (!headline || !body) { $("board-msg").textContent = "Write a headline and a message first."; return; }
    const store = loadStore();
    const slide = { id: "POST-" + Date.now(), tag: $("board-tag").value, headline: headline, body: body, date: todayISO(), by: POSTERS[ui.user.username], expires: null };
    store.unshift(slide);
    saveStore(store);
    e.target.reset();
    refresh(() => {
      const i = ui.slides.findIndex((s) => s.id === slide.id);
      if (i >= 0) goTo(i);
    });
    $("board-msg").textContent = "Posted to the board — everyone in the Portal will see it.";
    renderManage();
  }

  /* ---------------- assemble + render ---------------- */
  function refresh(after) {
    const manual = loadStore();
    const autoLocal = progactSlides(4);
    ui.slides = collect(manual, autoLocal);
    draw();
    renderComposer();
    startTimer();
    // Policies arrive asynchronously from the Documents gallery; when
    // they land, rebuild the deck (keeping the reader's place).
    if (typeof fetch === "function") {
      fetch("documents/policies/index.html").then((r) => (r && r.ok ? r.text() : "")).then((html) => {
        if (!html) return;
        const pol = policySlides(parseGallery(html), 5);
        if (!pol.length) return;
        const cur = ui.slides[ui.idx] && ui.slides[ui.idx].id;
        ui.slides = collect(manual, autoLocal.concat(pol));
        const ni = cur ? ui.slides.findIndex((s) => s.id === cur) : 0;
        ui.idx = ni >= 0 ? ni : 0;
        draw();
        startTimer();
      }).catch(() => { /* gallery unreachable — the board still shows posted + activity slides */ });
    }
    if (after) after();
  }
  function bindOnce() {
    if (ui.bound) return;
    ui.bound = true;
    const panel = $("message-board-panel");
    const prev = $("board-prev"), next = $("board-next");
    if (prev) prev.addEventListener("click", () => { step(-1); restart(); });
    if (next) next.addEventListener("click", () => { step(1); restart(); });
    if (panel) {
      panel.addEventListener("mouseenter", () => setPaused(true));
      panel.addEventListener("mouseleave", () => setPaused(false));
      panel.addEventListener("focusin", () => setPaused(true));
      panel.addEventListener("focusout", () => setPaused(false));
      panel.addEventListener("pointerdown", () => setPaused(!ui.paused));
    }
    const form = $("board-form");
    if (form) form.addEventListener("submit", onPost);
  }
  function render(user) {
    ui.user = user || null;
    bindOnce();
    refresh();
  }

  window.CPPBoard = {
    render,
    _test: { SEED, TAGS, POSTERS, BOARD_KEY, loadStore, saveStore, progactSlides, policySlides, parsePolicyDate, parseGallery, collect, nextIndex, normKey, policyNum, isLive, ui, step, goTo, onPost, ROTATE_MS }
  };
})();
